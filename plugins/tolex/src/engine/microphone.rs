//! Microphone — the mic model stage. Each model's signature
//! was DISTILLED FROM THE CORPUS: median dB difference vs the SM57
//! over matched (speaker, position) groups — the mic measured doing
//! its actual job on a guitar cab, placement habits included, no
//! datasheets (plugins/tolex/docs/corpus.md; analysis/ holds the
//! instrument). The signature is fitted to ten fixed sections
//! (0.5-0.7 dB rms); tests/mic_properties.rs pins the ENGINE against the
//! distilled tables, so the fit and the wiring answer to the corpus.
//! The SM57 is the flat reference — the cab's own voice IS the
//! 57-at-position picture the rest of the model was built on.

use stave_dsp::Biquad;
use stave_dsp::FilterSpec;

/// The corpus capture distance: the distilled signatures already
/// CARRY proximity at ~3 cm (York's close-mic practice) — the shelf
/// below is RELATIVE to this, unity at the default mic distance.
const R_REF_M: f32 = 0.03;
const C_AIR: f32 = 343.0;
/// Pressure-gradient fraction per model (params::MICS order): how
/// much of the pattern is figure-8. The 121 IS a ribbon figure-8;
/// dynamics are cardioid; the 160 is hypercardioid.
const GRADIENT: [f32; 8] = [0.5, 0.5, 0.5, 0.55, 0.5, 1.0, 0.75, 0.5];

/// LF boost of a pattern at distance r, dB at `f_lo` — the standard
/// gradient-mic proximity term blended by pattern.
fn prox_boost_db(g: f32, r_m: f32, f_lo: f32) -> f32 {
    let fc = C_AIR / (core::f32::consts::TAU * r_m.max(0.005));
    let b = (1.0 + (fc / f_lo) * (fc / f_lo)).sqrt();
    20.0 * ((1.0 - g) + g * b).max(1e-3).log10()
}

/// The relative proximity shelf for (model, mic distance): RBJ low
/// shelf, corner at the geometric mean of the two gradient corners,
/// gain = the LF boost difference (clamped ±12 dB). Zero at R_REF.
pub(crate) fn proximity_shelf(model: usize, mic_r_m: f32) -> (f32, f32) {
    let g = GRADIENT[model.min(GRADIENT.len() - 1)];
    let r = mic_r_m.max(0.005);
    // In the deep-LF limit relative proximity is pattern-blind (the
    // distance ratio dominates; the law's first read proved it) —
    // the pattern's purity shows in the TRANSITION band, where a
    // cardioid's omni half dilutes the gradient. The single-shelf
    // approximation carries that as a gain weight.
    let purity = 0.7 + 0.6 * g;
    let gain =
        ((prox_boost_db(g, r, 60.0) - prox_boost_db(g, R_REF_M, 60.0)) * purity).clamp(-14.0, 14.0);
    let fc_r = C_AIR / (core::f32::consts::TAU * r);
    let fc_ref = C_AIR / (core::f32::consts::TAU * R_REF_M);
    let corner = (fc_r * fc_ref).sqrt().clamp(60.0, 900.0);
    (corner, gain)
}

// Generated by analysis (corpus distillation vs SM57 + 10-section fit).
// Sections: (kind 0=LS/1=PK/2=HS, Hz, Q); gains per mic in dB.
pub(crate) const MIC_SECTIONS: [(u8, f32, f32); 10] = [
    (0, 120.0, 0.00),
    (1, 200.0, 1.00),
    (1, 350.0, 1.10),
    (1, 620.0, 1.10),
    (1, 1100.0, 1.10),
    (1, 1900.0, 1.10),
    (1, 3200.0, 1.20),
    (1, 5200.0, 1.20),
    (1, 8000.0, 1.30),
    (2, 9500.0, 0.00),
];
/// Gain rows follow params::MICS order; 57 is the flat reference.
pub(crate) const MIC_GAINS: [[f32; 10]; 8] = [
    [0.0; 10], // 57
    [
        4.73, 2.93, -0.65, 1.00, -1.48, 1.22, 4.07, 0.08, -4.12, 8.32,
    ], // 421
    [
        2.17, 0.01, 0.46, -0.74, 0.14, 0.43, 1.71, -0.78, -3.24, 1.73,
    ], // 58
    [
        -0.19, -1.70, 1.41, -0.60, 0.08, -0.32, 0.77, 1.24, -2.38, -1.57,
    ], // 906
    [
        2.95, -0.14, 1.21, -0.78, -0.01, 0.99, 2.28, -1.58, -3.46, 6.43,
    ], // SM7
    [
        9.75, 0.99, 2.33, 0.58, -0.83, -1.01, 3.06, -4.72, 0.09, -8.93,
    ], // 121
    [
        4.69, -0.25, 1.60, -0.29, -0.40, 0.95, 1.43, -2.35, -4.64, 1.35,
    ], // 160
    [
        7.14, 0.56, 1.68, 1.60, -2.26, 2.92, 2.40, -4.28, -3.25, 6.98,
    ], // U47
];

pub struct Microphone {
    sections: [Biquad; 10],
    proximity: Biquad,
    rate: f32,
}

impl Microphone {
    pub fn new() -> Self {
        Self {
            sections: [Biquad::new(); 10],
            proximity: Biquad::new(),
            rate: 0.0,
        }
    }

    pub fn prepare(&mut self, rate: f32) {
        self.rate = rate.max(1.0);
        for s in self.sections.iter_mut() {
            s.reset();
        }
        self.proximity.reset();
        self.set(0, R_REF_M);
    }

    /// Re-voice at block rate; state kept. `model` follows
    /// params::MICS order; `mic_r_m` sets the proximity lean.
    pub fn set(&mut self, model: usize, mic_r_m: f32) {
        let gains = &MIC_GAINS[model.min(MIC_GAINS.len() - 1)];
        for (k, (kind, hz, q)) in MIC_SECTIONS.iter().enumerate() {
            match kind {
                0 => self.sections[k].set(
                    FilterSpec::LowShelfRbj {
                        hz: *hz,
                        db: gains[k],
                    },
                    self.rate,
                ),
                2 => self.sections[k].set(
                    FilterSpec::HighShelfRbj {
                        hz: *hz,
                        db: gains[k],
                    },
                    self.rate,
                ),
                _ => self.sections[k].set(
                    FilterSpec::Peak {
                        hz: *hz,
                        db: gains[k],
                        q: *q,
                    },
                    self.rate,
                ),
            }
        }
        let (corner, gain) = proximity_shelf(model, mic_r_m);
        self.proximity.set(
            FilterSpec::LowShelfRbj {
                hz: corner,
                db: gain,
            },
            self.rate,
        );
    }

    #[inline]
    pub fn tick(&mut self, x: f32) -> f32 {
        let mut y = self.proximity.process(x);
        for s in self.sections.iter_mut() {
            y = s.process(y);
        }
        y
    }
}

/// The display twin — same tables, same setters, same shelf.
pub(crate) fn response_db(model: usize, mic_r_m: f32, hz: f32, rate: f32) -> f32 {
    let gains = &MIC_GAINS[model.min(MIC_GAINS.len() - 1)];
    let mut bq = Biquad::new();
    let (corner, gain) = proximity_shelf(model, mic_r_m);
    bq.set(
        FilterSpec::LowShelfRbj {
            hz: corner,
            db: gain,
        },
        rate,
    );
    let mut db = 20.0 * bq.magnitude_at(hz, rate).max(1e-12).log10();
    for (k, (kind, f0, q)) in MIC_SECTIONS.iter().enumerate() {
        match kind {
            0 => bq.set(
                FilterSpec::LowShelfRbj {
                    hz: *f0,
                    db: gains[k],
                },
                rate,
            ),
            2 => bq.set(
                FilterSpec::HighShelfRbj {
                    hz: *f0,
                    db: gains[k],
                },
                rate,
            ),
            _ => bq.set(
                FilterSpec::Peak {
                    hz: *f0,
                    db: gains[k],
                    q: *q,
                },
                rate,
            ),
        }
        db += 20.0 * bq.magnitude_at(hz, rate).max(1e-12).log10();
    }
    db
}
