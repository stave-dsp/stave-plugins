//! Anvil's typed parameter table. Identifiers are FOREVER — pick once,
//! never reuse or renumber.

extern crate alloc;
use alloc::sync::Arc;

use stave_core::params::{BoolParam, FloatParam, ParamFlags, Params, Range, Smooth, Taper, Unit};

// DEFAULTS = the rhythm brief (2026-07-26): load anvil into tolex
// and the pair IS the metalcore rig, no knob touched.
#[derive(Params)]
pub struct AnvilParameters {
    /// Preamp drive into the cascade, dB.
    pub preamp_gain: FloatParam,
    /// Pre-cascade highpass corner — how much low end is ALLOWED
    /// to reach the distortion. The chug knob.
    pub input_low_cut: FloatParam,
    /// The screamer out front (808-class feedback clipper): 0 = out
    /// of the path's way, up = the classic tight mid push.
    /// The stack, voiced around the metal V.
    pub bass_tone: FloatParam,
    pub midrange_tone: FloatParam,
    pub treble_tone: FloatParam,
    /// Power-section voicing around the squish.
    pub presence_tone: FloatParam,
    pub depth_tone: FloatParam,
    /// THE IMPOSSIBLE KNOB: how separately the lows and highs
    /// saturate. 0 = one honest tube path; 1 = the squash that stays
    /// focused (lows cannot intermodulate the teeth — a law).
    pub topology_separation_amount: FloatParam,
    /// SUB — the difference-tone octave (field-ratified SUBWIDE
    /// voicing): deep symmetric saturation of the low+lowmid band,
    /// output isolated below 175 Hz — everything there is
    /// GENERATED by the chord's own intermodulation (a power
    /// chord's f2-f1 IS the octave below the root, in tune by
    /// construction, no pitch tracking). 0 = off.
    pub difference_tone: FloatParam,
    /// EDGE — attack-bright depth on the bright branches (blocking-
    /// charge-driven: picks blaze, sustain folds). 0 = harmonics-
    /// at-the-top smooth; 1 = the white-noise-smoothed top.
    pub high_frequency_emphasis: FloatParam,
    /// Power squish drive — the squash's density.
    pub power_pair_overdrive: FloatParam,
    /// Output trim. Smoothing is DECLARED here (table-owned ramp),
    /// never hand-rolled in the engine.
    pub output_level: FloatParam,
    /// The framework gate owns click-free bypass; this carries the flag.
    pub bypass: BoolParam,
}

impl AnvilParameters {
    pub fn new() -> Arc<Self> {
        Arc::new(Self {
            // Range widened 24 -> 30 same-day pre-release (never shipped):
            // the knob is a CHARACTER sweep — loudness-compensated, so
            // the whole range is usable from a -18..-6 dBFS DI.
            preamp_gain: FloatParam::new(3, "gain", 18.0, Range::new(0.0, 30.0, Taper::Linear))
                .with_unit(Unit::Db { floor_db: None })
                .with_group("Gain"),
            input_low_cut: FloatParam::new(4, "tight", 120.0, Range::new(40.0, 300.0, Taper::Log))
                .with_unit(Unit::Hz)
                .with_group("Gain"),
            bass_tone: FloatParam::new(6, "bass", 6.25, Range::new(0.0, 10.0, Taper::Linear))
                .with_unit(Unit::Plain { decimals: 1 })
                .with_group("Tone"),
            midrange_tone: FloatParam::new(
                7,
                "mid",
                4.583_333,
                Range::new(0.0, 10.0, Taper::Linear),
            )
            .with_unit(Unit::Plain { decimals: 1 })
            .with_group("Tone"),
            treble_tone: FloatParam::new(8, "treble", 7.5, Range::new(0.0, 10.0, Taper::Linear))
                .with_unit(Unit::Plain { decimals: 1 })
                .with_group("Tone"),
            presence_tone: FloatParam::new(
                9,
                "presence",
                2.5,
                Range::new(-6.0, 6.0, Taper::Linear),
            )
            .with_unit(Unit::Db { floor_db: None })
            .with_group("Power"),
            depth_tone: FloatParam::new(10, "depth", 2.5, Range::new(-6.0, 6.0, Taper::Linear))
                .with_unit(Unit::Db { floor_db: None })
                .with_group("Power"),
            difference_tone: FloatParam::new(13, "sub", 0.0, Range::new(0.0, 1.0, Taper::Linear))
                .with_group("Voicing"),
            high_frequency_emphasis: FloatParam::new(
                14,
                "edge",
                0.0,
                Range::new(0.0, 1.0, Taper::Linear),
            )
            .with_group("Voicing"),
            topology_separation_amount: FloatParam::new(
                11,
                "focus",
                0.5,
                Range::new(0.0, 1.0, Taper::Linear),
            )
            .with_group("Gain"),
            power_pair_overdrive: FloatParam::new(
                12,
                "squash",
                12.0,
                Range::new(0.0, 18.0, Taper::Linear),
            )
            .with_unit(Unit::Db { floor_db: None })
            .with_group("Power"),
            output_level: FloatParam::new(1, "output", 0.0, Range::new(-24.0, 24.0, Taper::Linear))
                .with_unit(Unit::Db { floor_db: None })
                .with_group("Output")
                .with_smooth(Smooth::Exp { ms: 5.0 }),
            bypass: BoolParam::new(2, "bypass", false)
                .with_group("Output")
                .with_flags(ParamFlags {
                    bypass: true,
                    ..Default::default()
                }),
        })
    }
}
